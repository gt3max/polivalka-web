/**
 * admin-auth-gate.js — одна дверь для всех запросов админки.
 *
 * 🔴 Зачем. В admin.html сорок обращений к серверу, и все сорок идут МИМО
 * обёртки `API.fetch`: зовут `fetch` напрямую и вручную подставляют заголовок
 * с токеном. А обновление токена живёт именно в обёртке. Доступ живёт час —
 * и через час панель умирает целиком: пользователи, белый список, устройства,
 * архив, сводка задач, счета AWS. Обновление страницы не помогает (в хранилище
 * тот же протухший токен), а уход на страницу устройства и обратно лечит —
 * та страница ходит через обёртку и токен меняет.
 *
 * 🔴 Почему перехватчик, а не правка сорока мест. Панель сложная, данных много,
 * сорок механических замен — сорок шансов её уронить. Здесь одна вставка и
 * один проверяемый кусок логики. Тот же приём, что у `turso_guard` и
 * `cloudinary_guard` в скриптах: дверь ставится фактом подключения.
 *
 * Подключать ПЕРВЫМ после api-adapter.js, до любых загрузчиков.
 */
(function (глоб) {
  'use strict';

  function поставить(окно) {
    var исходный = окно.fetch;
    var идёт = null;            // единственное обновление на всех

    /** 🔴 Одно обновление на всех сразу. Загрузчиков около десятка и стартуют
     *  они разом: без этого они выпустят десять одновременных обновлений и
     *  затрут токен друг друга. */
    function обновить() {
      if (!идёт) {
        идёт = Promise.resolve(окно.Auth.refresh()).then(
          function (r) { идёт = null; return r; },
          function (e) { идёт = null; throw e; });
      }
      return идёт;
    }

    function наше(адрес) {
      var база = (окно.API && окно.API.cloudBase) || '';
      return база && String(адрес).indexOf(база) === 0;
    }

    /** 🔴 Сам `Auth.refresh()` ходит через fetch на `/auth/refresh`. Без этого
     *  исключения перехватчик вызовет сам себя — петля и мёртвая панель. */
    function это_вход(адрес) {
      return String(адрес).indexOf('/auth/') !== -1;
    }

    окно.fetch = function (адрес, настройки) {
      if (!наше(адрес) || это_вход(адрес)) {
        return исходный.call(окно, адрес, настройки);
      }
      var наст = настройки || {};

      function сходить() {
        //: 🔴 Заголовок пересобираем ЗДЕСЬ. Место вызова считает его до
        //: обновления токена — если не перекрыть, уйдёт старый.
        var шапка = {};
        var свои = наст.headers || {};
        for (var k in свои) if (Object.prototype.hasOwnProperty.call(свои, k)) шапка[k] = свои[k];
        var авто = окно.API.getAuthHeaders();
        for (var a in авто) if (Object.prototype.hasOwnProperty.call(авто, a)) шапка[a] = авто[a];
        var копия = {};
        for (var n in наст) if (Object.prototype.hasOwnProperty.call(наст, n)) копия[n] = наст[n];
        копия.headers = шапка;
        return исходный.call(окно, адрес, копия);
      }

      var начало = окно.Auth.isTokenExpired()
        ? обновить().then(сходить)
        : сходить();

      return начало.then(function (ответ) {
        //: Повтор РОВНО ОДИН. Сервер мог отказать и по другой причине —
        //: бесконечно долбиться в него нельзя.
        if (ответ && ответ.status === 401) {
          return обновить().then(function (получилось) {
            return получилось ? сходить() : ответ;
          });
        }
        return ответ;
      });
    }
    окно.fetch.__дверь = true;
    return окно.fetch;
  }

  if (typeof module !== 'undefined' && module.exports) {
    module.exports = { поставить: поставить };
  } else {
    поставить(глоб);
  }
})(typeof window !== 'undefined' ? window : globalThis);
