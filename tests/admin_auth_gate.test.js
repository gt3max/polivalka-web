/**
 * Дверь админки: токен обновляется сам, петли нет, обновление одно на всех.
 *
 * 🔴 Зачем. 23.09.2026 владелец видел живьём: панель открыта час → данные
 * исчезают → обновление страницы НЕ помогает → уход на устройство и обратно
 * лечит. Причина: сорок обращений в admin.html идут мимо обёртки, где живёт
 * обновление токена, а доступ живёт ровно час.
 *
 * Здесь проверяется логика двери без браузера: fetch, Auth и хранилище
 * подменены. Чего этот тест НЕ доказывает — что панель в живом браузере
 * переживёт час; это проверяется только владельцем.
 *
 * Запуск: node tests/admin_auth_gate.test.js
 */
const { поставить } = require('../admin-auth-gate.js');

let прошло = 0, упало = 0;
function проверить(имя, условие, пояснение) {
  if (условие) { прошло++; console.log('  ✅ ' + имя); }
  else { упало++; console.log('  ❌ ' + имя + (пояснение ? ' — ' + пояснение : '')); }
}

function стенд({ протух = false, ответы = [] } = {}) {
  const журнал = { запросов: [], обновлений: 0 };
  let очередь = ответы.slice();
  const окно = {
    API: {
      cloudBase: 'https://api.example',
      getAuthHeaders: () => ({ Authorization: 'Bearer ' + окно._токен }),
    },
    Auth: {
      isTokenExpired: () => протух,
      //: 🔴 Обновление НЕ мгновенное. С мгновенным проверка одновременности
      //: проходила бы сама собой: первый вызов успевал сбросить признак до
      //: того, как второй его прочитает, и тест зеленел на сломанном коде.
      //: Поймано подстановкой поломки 23.09.2026.
      refresh: () => new Promise((готово) => {
        журнал.обновлений++;
        setTimeout(() => {
          окно._токен = 'свежий';
          протух = false;
          готово(true);
        }, 20);
      }),
    },
    _токен: 'старый',
    fetch: async (адрес, настройки) => {
      журнал.запросов.push({ адрес, шапка: (настройки || {}).headers || {} });
      const код = очередь.length ? очередь.shift() : 200;
      return { status: код, ok: код < 400 };
    },
  };
  поставить(окно);
  return { окно, журнал };
}

(async function () {
  console.log('ДВЕРЬ АДМИНКИ (браузер не нужен)\n');

  // 1. протухший токен обновляется ДО запроса
  {
    const { окно, журнал } = стенд({ протух: true });
    await окно.fetch('https://api.example/admin/users', { headers: { Authorization: 'Bearer старый' } });
    проверить('протухший токен обновляется до запроса', журнал.обновлений === 1);
    проверить('в запрос ушёл СВЕЖИЙ заголовок, а не посчитанный местом вызова',
      журнал.запросов[0].шапка.Authorization === 'Bearer свежий',
      'ушло: ' + журнал.запросов[0].шапка.Authorization);
  }

  // 2. 401 → обновление и РОВНО один повтор
  {
    const { окно, журнал } = стенд({ ответы: [401, 200] });
    const ответ = await окно.fetch('https://api.example/admin/users', {});
    проверить('ответ 401 вызывает обновление', журнал.обновлений === 1);
    проверить('повтор ровно один', журнал.запросов.length === 2, 'запросов: ' + журнал.запросов.length);
    проверить('после повтора ответ успешный', ответ.status === 200);
  }

  // 3. 🔴 адрес входа идёт МИМО двери — иначе петля
  {
    const { окно, журнал } = стенд({ протух: true });
    await окно.fetch('https://api.example/auth/refresh', { method: 'POST' });
    проверить('/auth/ не перехватывается (нет петли)', журнал.обновлений === 0,
      'обновлений: ' + журнал.обновлений);
  }

  // 4. 🔴 десять одновременных запросов дают ОДНО обновление
  {
    const { окно, журнал } = стенд({ протух: true });
    await Promise.all(Array.from({ length: 10 }, (_, i) =>
      окно.fetch('https://api.example/admin/x' + i, {})));
    проверить('десять запросов разом — одно обновление', журнал.обновлений === 1,
      'обновлений: ' + журнал.обновлений);
    проверить('все десять ушли на сервер', журнал.запросов.length === 10);
  }

  // 5. чужие адреса дверь не трогает
  {
    const { окно, журнал } = стенд({ протух: true });
    await окно.fetch('https://ntfy.sh/тема', {});
    проверить('чужой адрес проходит без обновления', журнал.обновлений === 0);
  }

  console.log('\nитог: ' + прошло + ' прошло, ' + упало + ' упало');
  process.exit(упало ? 1 : 0);
})();
